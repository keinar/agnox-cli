import type { BrowserConfig } from "./analyzer.js";

/** Default Playwright version used when detection fails (published for both Node and Python images). */
export const PLAYWRIGHT_DEFAULT_VERSION = "1.65.1";

/** Default Python version for non-Playwright Pytest images. */
export const PYTHON_DEFAULT_VERSION = "3.12";

/** First Playwright versions published on Ubuntu 24.04 (noble) on MCR. Older versions only exist as jammy. */
const NOBLE_MIN_VERSION = { node: [1, 45], python: [1, 47] } as const;

function isAtLeast(version: string, [major, minor]: readonly number[]): boolean {
  const [maj = 0, min = 0] = version.split(".").map((n) => parseInt(n, 10) || 0);
  return maj > major || (maj === major && min >= minor);
}

/**
 * Official Playwright base image for a version: noble (Ubuntu 24.04) where it
 * is published, jammy (Ubuntu 22.04) for older pinned versions.
 */
export function playwrightBaseImage(version: string, flavor: "node" | "python"): string {
  const distro = isAtLeast(version, NOBLE_MIN_VERSION[flavor]) ? "noble" : "jammy";
  const repo = flavor === "node" ? "mcr.microsoft.com/playwright" : "mcr.microsoft.com/playwright/python";
  return `${repo}:v${version}-${distro}`;
}

/** Generates the Playwright Dockerfile with a dynamic image version. */
export function playwrightDockerfile(version: string): string {
  return `FROM ${playwrightBaseImage(version, "node")}

WORKDIR /app

COPY package*.json ./
RUN npm ci

COPY . .

RUN chmod +x /app/entrypoint.sh

# Do NOT add ENTRYPOINT or CMD: Agnox runs /bin/sh /app/entrypoint.sh <folder> itself.
`;
}

/**
 * Shared shell prologue: reads the run target and drops a baked-in local .env.
 *
 * Agnox passes the target as ONE argument: "all", one relative path, or up to 10
 * paths separated by single spaces (Smart PR routing). The platform validates
 * every path (no whitespace, globs or shell characters), so word splitting is
 * safe; globbing is disabled anyway.
 */
const ENTRYPOINT_PROLOGUE = `#!/bin/sh
# Generated by @agnox/agnox-cli for Agnox Hosted runs.
# Agnox runs: /bin/sh /app/entrypoint.sh "<target>"
#   <target> = "all" | one path | several paths separated by spaces (Smart PR)
set -f

TARGET="$1"

if [ -f .env ]; then
  echo "Removing local .env to enforce injected configuration..."
  rm .env
fi
`;

// Playwright entrypoint.sh template
export const PLAYWRIGHT_ENTRYPOINT = `${ENTRYPOINT_PROLOGUE}
echo "Running against BASE_URL: $BASE_URL"

# Agnox injects PLAYWRIGHT_REPORTERS (e.g. line,html,allure-playwright,json) so the
# JSON reporter always writes results.json for structured result parsing.
# Without it (manual invocation), playwright.config reporters apply.
REPORTER_FLAG=""
if [ -n "$PLAYWRIGHT_REPORTERS" ]; then
  REPORTER_FLAG="--reporter=$PLAYWRIGHT_REPORTERS"
fi

# Agnox injects PLAYWRIGHT_WORKERS to match the container's CPU quota.
WORKERS_FLAG=""
if [ -n "$PLAYWRIGHT_WORKERS" ]; then
  WORKERS_FLAG="--workers=$PLAYWRIGHT_WORKERS"
fi

export PLAYWRIGHT_JSON_OUTPUT_NAME="\${PLAYWRIGHT_JSON_OUTPUT_NAME:-/app/test-results/results.json}"

# Playwright treats arguments as file filters, so extra tokens that are not paths
# (e.g. "always run" patterns such as "smoke") still select tests. If none of the
# tokens exists as a path, the target likely belongs to another layout: run all.
FOUND_PATH=""
if [ -n "$TARGET" ] && [ "$TARGET" != "all" ]; then
  for P in $TARGET; do
    if [ -e "$P" ]; then
      FOUND_PATH="yes"
    fi
  done
fi

if [ -z "$TARGET" ] || [ "$TARGET" = "all" ]; then
  echo "Running ALL tests..."
  npx playwright test $REPORTER_FLAG $WORKERS_FLAG
elif [ -n "$FOUND_PATH" ]; then
  echo "Running targeted tests: $TARGET"
  npx playwright test $TARGET $REPORTER_FLAG $WORKERS_FLAG
else
  echo "Target '$TARGET' not found in container. Falling back to running ALL tests..."
  npx playwright test $REPORTER_FLAG $WORKERS_FLAG
fi
`;

// Pytest Dockerfile template
export interface PytestDockerfileOptions {
  pythonVersion: string;
  packageManager: "pip" | "poetry";
  installPlaywright: boolean;
  playwrightVersion?: string | null;
  browserConfig: BrowserConfig;
  extraSystemDeps: string[];
}

/** Base image the Pytest Dockerfile will use. */
export function pytestBaseImage(options: Pick<PytestDockerfileOptions, "pythonVersion" | "installPlaywright" | "playwrightVersion">): string {
  return options.installPlaywright
    ? playwrightBaseImage(options.playwrightVersion || PLAYWRIGHT_DEFAULT_VERSION, "python")
    : `python:${options.pythonVersion}-slim`;
}

export function generatePytestDockerfile(options: PytestDockerfileOptions): string {
  const { packageManager, browserConfig, extraSystemDeps } = options;

  let dockerfile = `FROM ${pytestBaseImage(options)}\n\n`;

  dockerfile += `WORKDIR /app\n\n`;

  // Install extra system dependencies if any
  if (extraSystemDeps.length > 0) {
    dockerfile += `RUN apt-get update && apt-get install -y --no-install-recommends \\\n`;
    dockerfile += `    ${extraSystemDeps.join(" ")} && \\\n`;
    dockerfile += `    rm -rf /var/lib/apt/lists/*\n\n`;
  }

  // Install dependencies based on package manager
  if (packageManager === "poetry") {
    dockerfile += `RUN pip install poetry\n`;
    dockerfile += `COPY pyproject.toml poetry.lock* ./\n`;
    dockerfile += `RUN poetry install --no-root\n\n`;
  } else {
    dockerfile += `COPY requirements.txt ./\n`;
    dockerfile += `RUN pip install --no-cache-dir -r requirements.txt\n\n`;
  }

  // Install specialized browser channel if needed (Chrome/Edge)
  if (browserConfig.dockerInstallCommand) {
    dockerfile += `# Required for specific browser channel\n`;
    dockerfile += `${browserConfig.dockerInstallCommand}\n\n`;
  }

  dockerfile += `COPY . .\n\n`;
  dockerfile += `RUN chmod +x /app/entrypoint.sh\n\n`;
  dockerfile += `# Do NOT add ENTRYPOINT or CMD: Agnox runs /bin/sh /app/entrypoint.sh <folder> itself.\n`;

  return dockerfile;
}

export interface PytestEntrypointOptions {
  packageManager: "pip" | "poetry";
  /** Write Allure results to /app/allure-results (collected by Agnox). Requires allure-pytest. */
  useAllure: boolean;
}

// Pytest entrypoint.sh template
export function generatePytestEntrypoint({ packageManager, useAllure }: PytestEntrypointOptions): string {
  const runPrefix = packageManager === "poetry" ? "poetry run " : "";
  const testCommand = `${runPrefix}pytest`;
  const allureFlag = useAllure ? " $ALLURE_FLAG" : "";

  // Only pass --alluredir when allure-pytest is installed in the image: pytest
  // rejects the unknown option and every run would fail otherwise.
  const allureCheck = useAllure
    ? `
ALLURE_FLAG=""
if ${runPrefix}python -c "import allure_pytest" >/dev/null 2>&1; then
  ALLURE_FLAG="--alluredir=allure-results"
else
  echo "allure-pytest is not installed in the image: skipping Allure results."
fi
`
    : "";

  return `${ENTRYPOINT_PROLOGUE}${allureCheck}
# pytest fails on a path that does not exist, so keep only the paths found in
# the image. If none is found, run the whole suite.
PATHS=""
if [ -n "$TARGET" ] && [ "$TARGET" != "all" ]; then
  for P in $TARGET; do
    if [ -e "$P" ]; then
      PATHS="$PATHS $P"
    else
      echo "Skipping '$P': not found in container."
    fi
  done
fi

if [ -z "$PATHS" ]; then
  echo "Running ALL tests..."
  ${testCommand}${allureFlag}
else
  echo "Running targeted tests:$PATHS"
  ${testCommand}$PATHS${allureFlag}
fi
`;
}

// Shared .dockerignore template.
// Local run artifacts must stay out of the image: Agnox collects /app/test-results,
// /app/allure-results etc. after the run, and a stale results.json baked into the
// image could be read as this run's result if the test runner crashes early.
export const DOCKERIGNORE = `.git
.env
node_modules
__pycache__
.venv
.pytest_cache
test-results
playwright-report
allure-results
allure-report
pytest-report
agnox-artifacts
`;
